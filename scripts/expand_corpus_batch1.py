def main() -> None:
    added, skipped = 0, 0
    for rel_path, qa_list in NEW_QA.items():
        path = CORPUS_DIR / rel_path
        if not path.exists():
            sys.exit(f"文件不存在: {rel_path}")
        text = path.read_text(encoding="utf-8")
        new_sections = []
        for q, a in qa_list:
            if f"## {q}" in text:
                skipped += 1
                continue
            new_sections.append(f"## {q}\n\n{a}\n")
        if new_sections:
            text = text.rstrip("\n") + "\n\n" + "\n".join(new_sections)
            path.write_text(text, encoding="utf-8")
            added += len(new_sections)
        print(f"  {rel_path}: +{len(new_sections)}")

    print(f"完成：新增 {added} 条QA，跳过已存在 {skipped} 条")


if __name__ == "__main__":
    main()
